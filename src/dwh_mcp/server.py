@mcp.tool()
async def gp_export(
    sql: str,
    output_path: str,
    format: str = "csv",
    alias: str | None = None,
    chunk_size: int = 10_000,
    delimiter: str = ",",
) -> str:
    """Выгрузить результат читающего SQL Greenplum в CSV, Parquet или Excel
    чанками, не более 1 000 000 строк. Не возвращает сами данные в модель.

    Вызывать только по явной просьбе пользователя, требует его согласования.
    Персональные данные выгружать нельзя. Запрос предварительно проверь через
    gp_query_test. При превышении лимита или ошибке файл не создаётся.

    Args:
        sql: один SELECT, можно с CTE, без персональных данных.
        output_path: абсолютный путь нового файла; расширение должно
            соответствовать формату (.csv, .parquet, .xlsx). Перезапись запрещена.
        format: csv, parquet или excel (также принимается xlsx).
        alias: контур из connections.yaml; по умолчанию — первый Greenplum.
        chunk_size: строк за чтение/запись, от 1 до 100 000; по умолчанию 10 000.
        delimiter: одиночный разделитель CSV; по умолчанию запятая.

    Возвращает JSON с путём, числом строк и размером файла.
    """
    return await _call(gp_export.export_query, sql, output_path, format, alias, chunk_size, delimiter)


